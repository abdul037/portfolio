/**
 * Extracts the literal content that lived inside the prototype's logic class —
 * the catalog index, the career Q&A entries, and the presentation-mode steps —
 * into a plain data module. These are content, not behaviour, so they belong
 * with the rest of the copy rather than inside the view model.
 *
 * Run: node scripts/port-site-data.mjs <handoff-design-dir>
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const srcDir = process.argv[2]
if (!srcDir) {
  console.error('usage: node scripts/port-site-data.mjs <handoff-design-dir>')
  process.exit(1)
}

const raw = readFileSync(join(srcDir, 'Portfolio v7.dc.html'), 'utf8')
  .replace(/(["'(=])assets\//g, '$1/assets/')
  .replace(/'Space Grotesk'/g, 'var(--font-space-grotesk)')
  .replace(/'IBM Plex Mono'/g, 'var(--font-ibm-plex-mono)')

/** Slice a balanced `[ … ]` literal starting at the first bracket after `marker`. */
function sliceArray(marker) {
  const start = raw.indexOf(marker)
  if (start < 0) throw new Error(`marker not found: ${marker}`)

  const open = raw.indexOf('[', start)
  let depth = 0
  let inString = null

  for (let i = open; i < raw.length; i++) {
    const ch = raw[i]

    if (inString) {
      if (ch === '\\') i++
      else if (ch === inString) inString = null
      continue
    }

    if (ch === "'" || ch === '"' || ch === '`') inString = ch
    else if (ch === '[') depth++
    else if (ch === ']') {
      depth--
      if (depth === 0) return raw.slice(open, i + 1)
    }
  }

  throw new Error(`unbalanced array for marker: ${marker}`)
}

/** Slice a balanced `{ … }` literal starting at the first brace after `marker`. */
function sliceObject(marker) {
  const start = raw.indexOf(marker)
  if (start < 0) throw new Error(`marker not found: ${marker}`)

  const open = raw.indexOf('{', start)
  let depth = 0
  let inString = null

  for (let i = open; i < raw.length; i++) {
    const ch = raw[i]

    if (inString) {
      if (ch === '\\') i++
      else if (ch === inString) inString = null
      continue
    }

    if (ch === "'" || ch === '"' || ch === '`') inString = ch
    else if (ch === '{') depth++
    else if (ch === '}') {
      depth--
      if (depth === 0) return raw.slice(open, i + 1)
    }
  }

  throw new Error(`unbalanced object for marker: ${marker}`)
}

/**
 * The catalog encodes "which modal does this card open" as an inline setState
 * callback. Behaviour belongs in the view model, so reduce each callback to the
 * modal key it targets — the prototype did the same thing at render time by
 * regex-matching its own callback source.
 */
function normaliseCatalog(source) {
  return source.replace(/onClick:\s*\(\)\s*=>\s*this\.setState\(\{\s*modal:\s*'([^']+)'\s*\}\)/g, "modal: '$1'")
}

const presSteps = sliceArray('presSteps = ')
const catalog = normaliseCatalog(sliceArray('const catalog = '))
const careerGulf = sliceArray("careerGulf: this.buildCareer('gulf',")
const careerRivigo = sliceArray("careerRivigo: this.buildCareer('rivigo',")
const careerAmazon = sliceArray("careerAmazon: this.buildCareer('amazon',")
const sectionMap = sliceObject('var sectionMap = ')
const modalMap = sliceObject('var modalMap = ')

const file = `// Generated by scripts/port-site-data.mjs from the design handoff package.
// Source: design_handoff_portfolio_site/design/Portfolio v7.dc.html
// Copy is the source of truth — edit here, not in the handoff.

/** One step of the guided walkthrough (press "p"). */
export interface PresStep {
  id: string
  label: string
  /** Section to scroll to. */
  section?: string
  /** Project modal to open. */
  modal?: string
  /** Agent deep-dive to open. */
  ha?: string
  /** Speaker note shown in the presenter bar. */
  note: string
}

/** A card in the master catalog — the single index tying every item together. */
export interface CatalogItem {
  name: string
  badge: string
  desc: string
  tags: string[]
  domain: string
  industry?: string
  /** Project key whose modal this card opens. */
  modal?: string
  imgId?: string
  imgHint?: string
  thumbSrc?: string
  [key: string]: any
}

/** One expandable row of a career accordion. */
export interface CareerEntry {
  q: string
  tag: string
  tagColor: string
  isStar?: boolean
  isList?: boolean
  isText?: boolean
  isMetrics?: boolean
  star?: { s: string; t: string; a: string; r: string }
  bullets?: string[]
  body?: string
  note?: string
  webApp?: { k: string; v: string }[]
  driverApp?: { k: string; v: string }[]
}

export const presSteps: PresStep[] = ${presSteps}

export const catalog: CatalogItem[] = ${catalog}

export const careerGulf: CareerEntry[] = ${careerGulf}

export const careerRivigo: CareerEntry[] = ${careerRivigo}

export const careerAmazon: CareerEntry[] = ${careerAmazon}

/** Terminal aliases that scroll to a section. */
export const sectionAliases: Record<string, string> = ${sectionMap}

/** Terminal aliases that open a project modal. */
export const modalAliases: Record<string, string> = ${modalMap}
`

writeFileSync('src/data/site.ts', file)
console.log(`src/data/site.ts (${catalog.split('\n').length} catalog lines)`)
